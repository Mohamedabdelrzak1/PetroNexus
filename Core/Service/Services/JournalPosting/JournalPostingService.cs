        // ─── PurchaseOrder Issuance ────────────────────────────────────────────
        // Debit:  Inventory (1301) — Cost of goods
        // Credit: Accounts Payable (2101) — Amount owed to Principal
        public async Task PostPurchaseOrderAsync(PurchaseOrder purchaseOrder, CancellationToken cancellationToken = default)
        {
            var transaction = await _unitOfWork.BeginTransactionAsync(cancellationToken);
            try
            {
                var inventoryAccount = await GetAccountByCodeAsync(AccountCodeInventory, cancellationToken);
                var apAccount = await GetAccountByCodeAsync(AccountCodeAccountsPayable, cancellationToken);

                var totalAmount = purchaseOrder.Items?.Sum(i => i.UnitCost * i.Quantity) ?? 0m;

                var entry = await CreateJournalEntryAsync(
                    "PurchaseOrder", purchaseOrder.Id,
                    purchaseOrder.Currency,
                    $"PO #{purchaseOrder.PoNumber} — Principal #{purchaseOrder.PrincipalId}",
                    new JournalEntryLineInput[]
                    {
                        new JournalEntryLineInput { Account = inventoryAccount, Debit = totalAmount, Credit = null, CostCenterId = purchaseOrder.TenderId },
                        new JournalEntryLineInput { Account = apAccount, Debit = null, Credit = totalAmount, CostCenterId = purchaseOrder.TenderId }
                    },
                    cancellationToken);

                purchaseOrder.JournalEntryId = entry.Id;
                _unitOfWork.Repository<PurchaseOrder, int>().Update(purchaseOrder);
                await _unitOfWork.SaveChangesAsync(cancellationToken);

                await transaction.CommitAsync(cancellationToken);
            }
            catch
            {
                await transaction.RollbackAsync(cancellationToken);
                throw;
            }
        }

        // ─── Shipment Costs ────────────────────────────────────────────────────
        // Debit:  Shipping Expense (5102) — Shipping + Customs
        // Credit: Cash/Bank (1101) — Amount paid
        public async Task PostShipmentAsync(Shipment shipment, CancellationToken cancellationToken = default)
        {
            var transaction = await _unitOfWork.BeginTransactionAsync(cancellationToken);
            try
            {
                var expenseAccount = await GetAccountByCodeAsync(AccountCodeShippingExpense, cancellationToken);
                var cashAccount = await GetAccountByCodeAsync(AccountCodeCash, cancellationToken);

                var totalCost = (shipment.ShippingCost ?? 0m) + (shipment.CustomsCost ?? 0m);
                if (totalCost <= 0) return; // No cost to post

                var entry = await CreateJournalEntryAsync(
                    "Shipment", shipment.Id,
                    CurrencyType.EGP, // Local costs
                    $"Shipment #{shipment.Id} — PO #{shipment.PurchaseOrderId} — Shipping & Customs",
                    new JournalEntryLineInput[]
                    {
                        new JournalEntryLineInput { Account = expenseAccount, Debit = totalCost, Credit = null, CostCenterId = shipment.PurchaseOrder.TenderId },
                        new JournalEntryLineInput { Account = cashAccount, Debit = null, Credit = totalCost, CostCenterId = shipment.PurchaseOrder.TenderId }
                    },
                    cancellationToken);

                shipment.JournalEntryId = entry.Id;
                _unitOfWork.Repository<Shipment, int>().Update(shipment);
                await _unitOfWork.SaveChangesAsync(cancellationToken);

                await transaction.CommitAsync(cancellationToken);
            }
            catch
            {
                await transaction.RollbackAsync(cancellationToken);
                throw;
            }
        }

        // ─── FabricationOrder Costs ────────────────────────────────────────────
