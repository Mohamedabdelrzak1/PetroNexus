        {
            var transaction = await _unitOfWork.BeginTransactionAsync(cancellationToken);
            try
            {
                var cashAccount = await GetAccountByCodeAsync(AccountCodeCash, cancellationToken);
                var commissionRevenueAccount = await GetAccountByCodeAsync(AccountCodeCommissionRevenue, cancellationToken);

                var entry = await CreateJournalEntryAsync(
                    "Commission", commission.Id,
                    commission.Currency,
                    $"Commission #{commission.Id} — Principal #{commission.PrincipalId} — PO #{commission.PurchaseOrderId}",
                    new JournalEntryLineInput[]
                    {
                        new JournalEntryLineInput { Account = cashAccount, Debit = commission.Amount, Credit = null, CostCenterId = null },
