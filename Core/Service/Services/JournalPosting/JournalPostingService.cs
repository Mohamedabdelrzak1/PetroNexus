using System;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using AutoMapper;
using Domain.Contracts;
using Domain.Enums;
using Domain.Models;
using ServiceAbstraction.IJournalPosting;

namespace Service.Services.JournalPosting
{
    /// <summary>
    /// Input model for journal entry line creation.
    /// </summary>
    public class JournalEntryLineInput
    {
        public Account Account { get; set; }
        public decimal? Debit { get; set; }
        public decimal? Credit { get; set; }
        public int? CostCenterId { get; set; }
    }

    public class JournalPostingService : IJournalPostingService
    {
        private readonly IUnitOfWork _unitOfWork;
        private readonly IMapper _mapper;

        // Default account codes
        private const string AccountCodeCash = "1101";
        private const string AccountCodeLCMargin = "1102";
        private const string AccountCodeAccountsReceivable = "1201";
        private const string AccountCodeInventory = "1301";
        private const string AccountCodeWIP = "1302";
        private const string AccountCodeAccountsPayable = "2101";
        private const string AccountCodeSalaryPayable = "2102";
        private const string AccountCodeRevenue = "4101";
        private const string AccountCodeCommissionRevenue = "4201";
        private const string AccountCodeSalaryExpense = "5101";
        private const string AccountCodeShippingExpense = "5102";
        private const string AccountCodeFabricationExpense = "5103";
        private const string AccountCodeCOGS = "5104";

        public JournalPostingService(IUnitOfWork unitOfWork, IMapper mapper)
        {
            _unitOfWork = unitOfWork ?? throw new ArgumentNullException(nameof(unitOfWork));
            _mapper = mapper ?? throw new ArgumentNullException(nameof(mapper));
        }

        private async Task<Account> GetAccountByCodeAsync(string code, CancellationToken cancellationToken)
        {
            var account = await _unitOfWork.Repository<Account, int>()
                .GetFirstOrDefaultAsync(a => a.Code == code, null, false, cancellationToken);
            return account ?? throw new InvalidOperationException($"Account with code '{code}' not found. Please seed the chart of accounts first.");
        }

        private async Task<decimal> GetExchangeRateAsync(CurrencyType fromCurrency, CurrencyType toCurrency, CancellationToken cancellationToken)
        {
            if (fromCurrency == toCurrency)
                return 1m;

            var rate = await _unitOfWork.Repository<ExchangeRate, int>()
                .GetFirstOrDefaultAsync(
                    r => r.FromCurrency == fromCurrency && r.ToCurrency == toCurrency,
                    null, false, cancellationToken);

            if (rate != null)
                return rate.Rate;

            // Try reverse rate
            var reverseRate = await _unitOfWork.Repository<ExchangeRate, int>()
                .GetFirstOrDefaultAsync(
                    r => r.FromCurrency == toCurrency && r.ToCurrency == fromCurrency,
                    null, false, cancellationToken);

            if (reverseRate != null && reverseRate.Rate != 0)
                return 1m / reverseRate.Rate;

            // Default: assume 1:1 if no rate found (for EGP base)
            return 1m;
        }

        private async Task<JournalEntry> CreateJournalEntryAsync(
            string sourceType, int sourceId,
            CurrencyType currency, string description,
            JournalEntryLineInput[] lines,
            CancellationToken cancellationToken)
        {
            var baseCurrency = CurrencyType.EGP;
            var exchangeRate = await GetExchangeRateAsync(currency, baseCurrency, cancellationToken);

            var entry = new JournalEntry
            {
                ReferenceNumber = $"JE-{sourceType}-{sourceId}-{DateTime.UtcNow:yyyyMMddHHmmss}",
                EntryDate = DateTime.UtcNow,
                Description = description,
                Currency = currency,
                SourceType = sourceType,
                SourceId = sourceId,
                IsAutoGenerated = true
            };

            await _unitOfWork.Repository<JournalEntry, int>().AddAsync(entry, cancellationToken);
            await _unitOfWork.SaveChangesAsync(cancellationToken);

            foreach (var line in lines)
            {
                var debit = line.Debit ?? 0m;
                var credit = line.Credit ?? 0m;

                var entryLine = new JournalEntryLine
                {
                    JournalEntryId = entry.Id,
                    AccountId = line.Account.Id,
                    CostCenterId = line.CostCenterId,
                    Debit = debit,
                    Credit = credit,
                    ExchangeRateToBase = exchangeRate,
                    DebitBaseCurrency = debit * exchangeRate,
                    CreditBaseCurrency = credit * exchangeRate
                };

                await _unitOfWork.Repository<JournalEntryLine, int>().AddAsync(entryLine, cancellationToken);
            }

            await _unitOfWork.SaveChangesAsync(cancellationToken);

            // Reload to verify balance
            var savedEntry = await _unitOfWork.Repository<JournalEntry, int>()
                .GetFirstOrDefaultAsync(e => e.Id == entry.Id, null, false, cancellationToken);

            if (savedEntry != null && !savedEntry.IsBalanced)
            {
                throw new InvalidOperationException(
                    $"JournalEntry #{entry.Id} is not balanced! " +
                    $"TotalDebitBase={savedEntry.TotalDebitBase}, TotalCreditBase={savedEntry.TotalCreditBase}");
            }

            return entry;
        }

        // ─── Invoice Issuance ──────────────────────────────────────────────────
        // Debit:  Accounts Receivable (1201) — Amount owed by client
        // Credit: Revenue (4101) — Invoice total
        public async Task PostInvoiceAsync(Invoice invoice, CancellationToken cancellationToken = default)
        {
            var transaction = await _unitOfWork.BeginTransactionAsync(cancellationToken);
            try
            {
                var arAccount = await GetAccountByCodeAsync(AccountCodeAccountsReceivable, cancellationToken);
                var revenueAccount = await GetAccountByCodeAsync(AccountCodeRevenue, cancellationToken);

                var entry = await CreateJournalEntryAsync(
                    "Invoice", invoice.Id,
                    invoice.Currency,
                    $"Invoice #{invoice.InvoiceNumber} — Client #{invoice.ClientId}",
                    new JournalEntryLineInput[]
                    {
                        new JournalEntryLineInput { Account = arAccount, Debit = invoice.TotalAmount, Credit = null, CostCenterId = invoice.TenderId },
                        new JournalEntryLineInput { Account = revenueAccount, Debit = null, Credit = invoice.TotalAmount, CostCenterId = invoice.TenderId }
                    },
                    cancellationToken);

                invoice.JournalEntryId = entry.Id;
                _unitOfWork.Repository<Invoice, int>().Update(invoice);
                await _unitOfWork.SaveChangesAsync(cancellationToken);

                await transaction.CommitAsync(cancellationToken);
            }
            catch
            {
                await transaction.RollbackAsync(cancellationToken);
                throw;
            }
        }

        // ─── Payment Received ──────────────────────────────────────────────────
        // Debit:  Cash/Bank (1101) — Amount received
        // Credit: Accounts Receivable (1201) — Reduces client's balance
